"""Все настройки пайплайна в одном месте.

Числа подобраны под то, как устроен сам homr (см. omr/README.md):
он ужимает картинку до ФИКСИРОВАННОЙ ширины 1920 px и только потом гоняет
сегментацию. Поэтому каждый пиксель, потраченный на стол/фон вокруг листа,
буквально отнимается у нотных линеек — отсюда и цель пайплайна: отдать движку
кадр, в котором лист занимает все 1920 px и лежит ровно.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class PipelineConfig:
    # --- Рабочее разрешение анализа -------------------------------------------------
    # Геометрию (перекос, углы страницы, кривизну) ищем на уменьшенной копии: это
    # в разы быстрее и УСТОЙЧИВЕЕ — мелкий шум сенсора усредняется. Все найденные
    # координаты потом масштабируются обратно и применяются к оригиналу, так что
    # ремап делается ровно один раз и по полному разрешению.
    analysis_width: int = 1400
    # Если на этой ширине станов нашлось меньше, чем `analysis_enough_staves`,
    # разбор повторяется подробнее (вплоть до `max_analysis_width`). Порог именно
    # «комфортный», а не минимальный: трёх станов хватает, чтобы ПОСТРОИТЬ
    # четырёхугольник, но если их всего три на целой странице — значит лист в
    # кадре мелкий, детектор видит меньшую часть музыки, и рамка выйдет кривой.
    analysis_enough_staves: int = 6
    max_analysis_width: int = 2800
    # Насколько больше станов должно найтись на повёрнутой копии, чтобы поверить
    # в альбомную ориентацию. Запас нужен, чтобы шум не переворачивал страницу,
    # на которой и так что-то нашлось.
    orientation_margin: int = 2

    # --- Детекция нотных линеек ------------------------------------------------------
    # Максимальный перекос, который вообще пытаемся исправить. Больше 12° для
    # снимка листа нереалистично, а широкий диапазон только плодит ложные углы.
    max_skew_deg: float = 12.0
    # Минимальная длина отрезка, чтобы считать его нотной линейкой (доля ширины).
    # Нотные линейки — самые длинные горизонтальные штрихи на странице; текст и
    # лиги короче.
    min_line_len_ratio: float = 0.08
    # Максимальная толщина линейки (доля высоты). Отсекает балки и заливки.
    max_line_thickness_ratio: float = 0.006

    # --- Поиск страницы --------------------------------------------------------------
    # Сколько нужно станов, чтобы доверять «нотной» оценке четырёхугольника.
    min_staves_for_quad: int = 3
    # Насколько расширить найденный блок нот наружу (доля его размера), чтобы не
    # срезать заголовок, добавочные линейки и текст под станом.
    quad_margin: float = 0.06
    # Четырёхугольник меньше/больше этих долей кадра считаем мусорным.
    # Для контурной оценки порог высокий: контур меньше четверти кадра — это почти
    # наверняка не лист, а какой-то объект на столе. Для оценки по нотам порог
    # низкий: блок нот на снимке разворота или листа издалека занимает считаные
    # проценты кадра, и это ровно тот случай, ради которого всё затевалось.
    min_quad_area_ratio: float = 0.25
    min_staff_quad_area_ratio: float = 0.02
    max_quad_area_ratio: float = 0.995

    # --- Выпрямление кривизны (dewarp) ----------------------------------------------
    min_lines_for_dewarp: int = 6
    # Степень многочлена, которым описывается форма линейки. Изогнутая страница —
    # кусок цилиндра, четвёртой степени на её сечение хватает с запасом, а всё
    # сверх неё — это уже подгонка под шум трассировки.
    dewarp_polynomial_degree: int = 4
    # Меньше этой амплитуды кривизну не трогаем — ремап только размоет картинку.
    min_dewarp_amplitude_px: float = 2.5
    # Больше этой (доля высоты) — не верим оценке и не трогаем.
    max_dewarp_amplitude_ratio: float = 0.15
    # Растягивать X по длине дуги только если сжатие заметное.
    arc_correction_min_ratio: float = 1.002

    # --- Финальный доворот ------------------------------------------------------------
    deskew_min_deg: float = 0.05
    deskew_max_passes: int = 2

    # --- Нормализация ------------------------------------------------------------------
    # Ядро морфологической оценки фона (доля меньшей стороны).
    illumination_kernel_ratio: float = 0.02
    # Ровно столько, сколько homr и так сделает сам — значит его resize станет
    # no-op и мы не потеряем ничего на лишней интерполяции.
    target_width: int = 1920
    # Апскейлить сверх этого бессмысленно: новых деталей не появится.
    max_upscale: float = 2.0
    # Коридор межлинейного расстояния на выходе. Ниже нижней границы сегментация
    # homr перестаёт разделять линейки, выше — стан не влезает в его канву.
    min_interline_px: float = 7.0
    max_interline_px: float = 26.0

    # --- Разворот книги (две страницы в кадре) ---
    # Провал покрытия в середине блока нот, ниже которого считаем, что нашли
    # корешок. Замеры на реальных файлах: развороты дают 0.02, одиночные
    # страницы 0.90+, так что порог посередине берётся с огромным запасом.
    spread_gutter_ratio: float = 0.25
    # Меньше этого числа фрагментов линеек — сигналу верить нельзя.
    spread_min_fragments: int = 40
    # Какая доля фрагментов должна остаться по КАЖДУЮ сторону от разреза.
    # Иначе мы режем не корешок, а поле страницы.
    spread_min_side_share: float = 0.25

    # --- Повтор движка --------------------------------------------------------------
    # Если homr нашёл станов МЕНЬШЕ, чем наш детектор на той же картинке, он стан
    # потерял: на скриншоте Шопена op.10 №3 — 9 из 10, одна рука системы пропала
    # (91% -> 80%). Сбой воспроизводится на тех же пикселях и уходит от лёгкого
    # размытия или белых полей (помогли 4 варианта из 5). Повторяем по очереди, до
    # первого варианта, где станов столько же, сколько у нас. Пусто — без повтора.
    # На наборе эталонов расхождение было на 2 страницах из 77, одно из них ложное
    # (наш детектор насчитал лишний стан) — там повтор просто стоит времени.
    engine_retry_variants: tuple[str, ...] = ("blur", "pad")

    # --- Страховка ---------------------------------------------------------------------
    # После всех стадий пересчитываем нотные линейки. Если их стало заметно
    # меньше, чем было на входе, — пайплайн сделал хуже, отдаём оригинал.
    safety_check: bool = True
    safety_min_ratio: float = 0.75


DEFAULT = PipelineConfig()
